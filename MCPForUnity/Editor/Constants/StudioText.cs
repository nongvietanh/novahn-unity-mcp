        public static string T(string english)
        {
            if (string.IsNullOrEmpty(english)) return english;
            if (McpUiLocalization.CurrentLanguage == "vi")
                return Vietnamese.TryGetValue(english, out var value) ? value : McpUiLocalization.Translate(english);
            foreach (var pair in Vietnamese) if (pair.Value == english) return pair.Key;
            return McpUiLocalization.Translate(english);
        }
